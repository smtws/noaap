"""FLAC and MP3: four containers, one vocabulary (DESIGN §9, slice 53).

Until 1.0.0 this program could read and write two of them. Everything that was not `.m4a` was
opened as Opus, so a `.flac` raised inside `audio_length`, was caught, and came back `None` — and a
`None` length reads as "no match" while an empty quality reads as "unknown". Nothing failed and no
test noticed, because no test had ever seen a FLAC. **That is the defect these cases exist for**,
and the first one fails against 1.0.0.

The files are generated by ffmpeg at test time; no audio lives in the repository.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest
from mutagen.flac import FLAC
from mutagen.id3 import ID3
from mutagen.mp3 import MP3
from test_media import JPEG, make_plan

from noaap.tag import audio_length, audio_quality, kind, tag_file, tagged_lyrics

SECOND = ["-f", "lavfi", "-i", "sine=duration=1"]


def encode(path: Path, *args: str) -> Path:
    if not shutil.which("ffmpeg"):
        pytest.skip("ffmpeg not installed")
    subprocess.run(["ffmpeg", "-v", "error", *SECOND, *args, str(path)], check=True)
    return path


@pytest.fixture
def flac_file(tmp_path) -> Path:
    return encode(tmp_path / "t.flac", "-c:a", "flac", "-ar", "44100", "-metadata", "title=junk")


@pytest.fixture
def mp3_file(tmp_path) -> Path:
    return encode(tmp_path / "t.mp3", "-c:a", "libmp3lame", "-b:a", "192k", "-metadata", "title=junk")


@pytest.fixture
def opus_file(tmp_path) -> Path:
    return encode(tmp_path / "t.opus", "-c:a", "libopus")


@pytest.fixture
def m4a_file(tmp_path) -> Path:
    return encode(tmp_path / "t.m4a", "-c:a", "aac", "-b:a", "128k")


# -- reading -------------------------------------------------------------------------------------


def test_a_flac_has_a_length_and_a_quality(flac_file):
    """The regression, stated as plainly as it deserves: this answered None and {}."""
    assert audio_length(flac_file) == pytest.approx(1.0, abs=0.1)

    quality = audio_quality(flac_file)
    assert quality["codec"] == "flac"
    assert quality["sample_rate"] == 44100 and quality["channels"] == 1
    assert quality["bitrate"] > 0


def test_an_mp3_has_a_length_and_a_quality(mp3_file):
    assert audio_length(mp3_file) == pytest.approx(1.0, abs=0.2)

    quality = audio_quality(mp3_file)
    assert quality["codec"] == "mp3"
    assert quality["sample_rate"] == 44100
    assert 150_000 < quality["bitrate"] < 210_000


@pytest.mark.parametrize("name,expected", [("a.opus", "opus"), ("a.flac", "flac"), ("a.mp3", "mp3"),
                                           ("a.m4a", "mp4"), ("a.mp4", "mp4"), ("a.MP3", "mp3"),
                                           ("a.weird", "opus")])
def test_the_container_is_decided_in_one_place(name, expected):
    """An unknown suffix still reads as Opus — that is what every download is, and guessing
    anything else would turn an odd name into an unreadable file."""
    assert kind(Path(name)) == expected


def test_every_container_measures(opus_file, flac_file, mp3_file, m4a_file):
    for path in (opus_file, flac_file, mp3_file, m4a_file):
        assert audio_length(path) is not None, path.suffix
        assert audio_quality(path).get("codec"), path.suffix


def test_something_that_is_not_audio_is_still_an_unknown_not_a_crash(tmp_path):
    not_audio = tmp_path / "sleeve.flac"
    not_audio.write_bytes(b"<html>a consent page</html>")

    assert audio_length(not_audio) is None
    assert audio_quality(not_audio) == {}


