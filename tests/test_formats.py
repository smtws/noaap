def test_a_length_of_zero_is_unknown_and_not_a_short_track(tmp_path, monkeypatch):
    """Three albums in the reference collection are FLACs whose STREAMINFO says `total_samples = 0`.
    A 0 there is a gap the encoder never filled in, not a measurement — and read as a number it
    made 52 real tracks "shorter than 30s", which is how an intro card is recognised and dropped."""
    from noaap import tag

    path = tmp_path / "t.flac"
    path.write_bytes(b"not read: the info object is the thing under test")

    class Silent:
        info = type("info", (), {"length": 0.0})()

    monkeypatch.setattr(tag, "_open", lambda p: Silent())

    assert tag.audio_length(path) is None


def test_a_local_address_is_not_written_into_the_file(tmp_path):
    """`source` is there so whoever opens the file later can go back to where it came from. A
    folder's address is the user's own directory — it identifies the album to nobody, and putting
    it in every file carries a home path around. Found by reading the tags of a real intake."""
    from noaap.tag import build_tags

    plan = make_plan()
    plan.source_url = "/home/someone/Music/legacy/A Band/An Album"

    assert "source" not in build_tags(plan, plan.tracks[0])

    plan.source_url = "https://www.youtube.com/playlist?list=PLx"
    assert build_tags(plan, plan.tracks[0])["source"] == plan.source_url


def test_a_length_is_measured_once_and_the_same_way_everywhere(tmp_path, monkeypatch):
    """The acceptance run found 52 tracks with no `file_length` although their candidate held a
    decoded one: the download path read the header only. Every place that needs this file's own
    seconds — the plan's `file_length`, the LRCLIB match, the vendor's bill — asks the same
    function now, and `_measure_candidate` never trades a number it has for an absence."""
    from noaap import tag
    from noaap.download import _measure_candidate
    from noaap.models import Candidate, PlanTrack

    path = tmp_path / "t.flac"
    path.write_bytes(b"stands in for a file whose header will not answer")
    monkeypatch.setattr(tag, "audio_length", lambda p: None)
    monkeypatch.setattr(tag, "decoded_length", lambda p: 269.7)

    assert tag.measured_length(path) == 269.7

    track = PlanTrack(video_id="x", number=1, artist="A", title="t", filename="t.flac",
                      provenance={}, candidates=[Candidate(ref="x", length=269.7)], chosen="x")
    track.file_length = None
    _measure_candidate(track, path)

    assert track.candidate("x").length == 269.7, "a known length survives a file that will not say"


def _three_discs():
    """A plan whose discs are of different lengths, and whose numbers restart on each — which is
    what the user's own library does: 52 discs across 23 albums, numbered 1..n within the disc."""
    from noaap.models import AlbumPlan, Kind, PlanTrack

    tracks = [PlanTrack(video_id=f"v{d}{n}", number=n, artist="A", title=f"T{d}-{n}",
                        filename=f"{d}-{n}.x", provenance={}, disc=d)
              for d, many in ((1, 3), (2, 1), (3, 2)) for n in range(1, many + 1)]
    return AlbumPlan(source_url="https://www.youtube.com/playlist?list=PLx", source_id="PLx",
                     kind=Kind.OFFICIAL_ALBUM, album="Alles", albumartist="Aphelion", year=None,
                     cover_url=None, folder="x", tracks=tracks)


def test_a_track_total_is_the_count_of_its_own_disc(flac_file, mp3_file, m4a_file):
    """And the count of discs is a field of its own (§9, slice 102).

    All three writers used `len(plan.tracks)` — the whole album — so every track of a three-disc set
    said 29 of 29, and only the m4a writer ever said how many discs there were. Measured in the
    user's own library before the fix: **627 files across 23 albums**, every one of them wrong, and
    0 of 627 carrying a disc total at all. A single-disc album's two numbers are equal, which is why
    nothing noticed.
    """
    from mutagen.mp4 import MP4

    plan = _three_discs()
    second = next(t for t in plan.tracks if t.disc == 2)      # the only track on disc 2

    tag_file(flac_file, plan, second)
    assert FLAC(flac_file)["tracktotal"] == ["1"] and FLAC(flac_file)["totaltracks"] == ["1"]
    assert FLAC(flac_file)["disctotal"] == ["3"] and FLAC(flac_file)["totaldiscs"] == ["3"]

    tag_file(mp3_file, plan, second)
    assert ID3(mp3_file)["TRCK"].text == ["1/1"] and ID3(mp3_file)["TPOS"].text == ["2/3"]

    tag_file(m4a_file, plan, second)
    assert MP4(m4a_file)["trkn"] == [(1, 1)] and MP4(m4a_file)["disk"] == [(2, 3)]

    third = next(t for t in plan.tracks if t.disc == 3)       # a disc of two
    tag_file(flac_file, plan, third)
    assert FLAC(flac_file)["tracktotal"] == ["2"], "its own disc, not the album's nine"


def test_the_disc_totals_read_back_as_they_were_written(flac_file, mp3_file, m4a_file):
    """Which is the half that keeps the dry run honest (§9, slice 85).

    `TPOS` went through the key loop that reads a frame's whole text, so a file noaap had just
    written would come back with `discnumber` = "2/3" and be compared against "2" — and every pass
    would say, for ever, that it needs retagging.
    """
    from noaap.tag import tags_in

    plan = _three_discs()
    second = next(t for t in plan.tracks if t.disc == 2)
    for path in (flac_file, mp3_file, m4a_file):
        tag_file(path, plan, second)
        got = tags_in(path)
        assert (got["tracknumber"], got["tracktotal"], got["totaltracks"]) == ("1", "1", "1"), path.suffix
        assert (got["discnumber"], got["disctotal"], got["totaldiscs"]) == ("2", "3", "3"), path.suffix


def _disc_plan(shape, totals=None):
    """A plan whose discs hold the given track numbers, each file remembering `totals` as its own."""
    from noaap.models import AlbumPlan, Kind, PlanTrack

    tracks = []
    for disc, numbers in shape.items():
        for n in numbers:
            track = PlanTrack(video_id=f"v{disc}{n}", number=n, artist="A", title=f"T{disc}-{n}",
                              filename=f"{disc}-{n}.opus", provenance={}, disc=disc)
            if totals is not None and disc in totals:
                track.adopted_tags = {"tracktotal": [str(totals[disc])]}
            tracks.append(track)
    return AlbumPlan(source_url="https://www.youtube.com/playlist?list=PLx", source_id="PLx",
                     kind=Kind.OFFICIAL_ALBUM, album="Alles", albumartist="Aphelion", year=None,
                     cover_url=None, folder="x", tracks=tracks)


def test_a_disc_total_is_never_below_the_highest_number_on_it():
    """The user, on the count of tracks present: *"it could have track 10 of 9? that'd be odd"*.

    It could, and on 8 of the 52 discs in their own collection it would have. The five cases of the
    rule (R-346), in its order.
    """
    full = _disc_plan({1: [1, 2, 3], 2: [1, 2]})
    assert full.disc_length(1) == 3 and full.disc_length(2) == 2, "a full disc: count = highest"

    gapped = _disc_plan({1: [1, 2, 3], 2: [1, 3, 11]})
    assert gapped.disc_length(2) == 11, "no remembered total: the highest number, not the three present"

    remembered = _disc_plan({1: [1, 2, 3], 2: [1, 3, 11]}, totals={2: 12})
    assert remembered.disc_length(2) == 12, "every file said twelve, and twelve is credible: kept"

    disagree = _disc_plan({1: [1, 2, 3], 2: [1, 3, 11]})
    disagree.tracks[-1].adopted_tags = {"tracktotal": ["12"]}
    assert disagree.disc_length(2) == 11, "the files do not agree, so they are not evidence"

    impossible = _disc_plan({1: [1, 2, 3], 2: [1, 3, 11]}, totals={2: 3})
    assert impossible.disc_length(2) == 11, "three is below the highest number present: set aside"

    one_disc = _disc_plan({1: [1, 2, 3, 4]})
    assert one_disc.disc_length(1) == 4, "a single-disc album is unchanged"


def test_the_albums_own_length_is_not_evidence_about_a_disc():
    """Which is the one place the ordering cannot be read literally.

    Before this, noaap wrote the album's track count into every file — so for all 23 multi-disc
    albums in the user's collection "what every file already said" is the album's length: agreed by
    every track, not below any number, and wrong. Taking it would have left all 627 files as they are.
    """
    theirs = _disc_plan({1: [1, 2, 3], 2: [1, 2]}, totals={1: 5, 2: 5})   # five tracks in all
    assert theirs.disc_length(1) == 3 and theirs.disc_length(2) == 2

    # the same number, where it is *not* the album's length, is kept
    credible = _disc_plan({1: [1, 2, 3], 2: [1, 2]}, totals={1: 5})
    credible.tracks.append(credible.tracks[-1])          # six tracks now, so five means something
    assert credible.disc_length(1) == 5


def test_one_open_answers_everything_the_old_three_did(flac_file, mp3_file, opus_file, m4a_file):
    """Reading a file once must say exactly what reading it four times said (§9, slice 105).

    `read_tags`, `audio_length` and `audio_quality` each opened the file for themselves — four opens
    in all, two of them inside `audio_quality` — and a share re-reads on every one: a dry run of
    `take-in` over the user's own collection read **2.7 times the whole collection**, 80.75 GB for
    41 GB of music, where the dry run's own work is 2.3 MB of an album. The values may not move.
    """
    from noaap.sources_folder import measure, read_tags
    from noaap.tag import audio_length, audio_quality, reading

    plan = make_plan()
    for path in (flac_file, mp3_file, opus_file, m4a_file):
        tag_file(path, plan, plan.tracks[0], cover=JPEG)       # something in every field
        apart = (read_tags(path), audio_length(path), audio_quality(path))
        with reading(path) as one:
            together = (read_tags(path, one), audio_length(path, one), audio_quality(path, one))
        assert apart == together, path.suffix

        # and the measurement built on them, which is what an adoption records
        separately = measure(path, digest=False)
        with reading(path) as one:
            shared = measure(path, digest=False, one=one)
        assert separately == shared, path.suffix


def test_a_file_that_cannot_be_read_still_answers_nothing(tmp_path):
    """One open that fails must read as the old four did: no length, no quality, no tags, no raising."""
    from noaap.sources_folder import read_tags
    from noaap.tag import audio_length, audio_quality, reading

    broken = tmp_path / "not really.mp3"
    broken.write_bytes(b"this is not an mp3")
    with reading(broken) as one:
        assert audio_length(broken, one) is None
        assert audio_quality(broken, one) == {}
        assert read_tags(broken, one) == {}

    gone = tmp_path / "not there at all.flac"
    with reading(gone) as one:
        assert audio_length(gone, one) is None
        assert audio_quality(gone, one) == {}
        assert read_tags(gone, one) == {}
