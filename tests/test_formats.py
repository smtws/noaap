def test_a_flac_is_tagged_and_carries_its_cover(flac_file):
    plan = make_plan()
    tag_file(flac_file, plan, plan.tracks[0], cover=JPEG)

    tags = FLAC(flac_file)
    assert tags["title"] == ["T1"] and tags["artist"] == ["A1"]
    assert tags["albumartist"] == ["My Dark Lullabies"]
    assert tags["album"] == ["Vol. 1 - Heavy Sleeping"]
    assert tags["tracknumber"] == ["1"] and tags["tracktotal"] == ["2"]
    assert tags["compilation"] == ["1"]
    assert len(tags.pictures) == 1 and tags.pictures[0].data == JPEG
    assert tags.pictures[0].type == 3


def test_an_mp3_is_tagged_and_carries_its_cover(mp3_file):
    plan = make_plan()
    tag_file(mp3_file, plan, plan.tracks[0], cover=JPEG)

    tags = ID3(mp3_file)
    assert tags["TIT2"].text == ["T1"] and tags["TPE1"].text == ["A1"]
    assert tags["TPE2"].text == ["My Dark Lullabies"]
    assert tags["TALB"].text == ["Vol. 1 - Heavy Sleeping"]
    assert tags["TRCK"].text == ["1/2"], "ID3 counts within the total, in one frame"
    assert tags["TCMP"].text == ["1"]
    assert tags["APIC:Cover"].data == JPEG
    assert tags["TXXX:source"].text == [plan.source_url], "not COMM: that is where people keep notes"


def test_a_disc_number_is_written_only_when_there_is_more_than_one(mp3_file, flac_file):
    one, many = make_plan(), make_plan(discs=2)

    tag_file(mp3_file, one, one.tracks[0])
    tag_file(flac_file, one, one.tracks[0])
    assert "TPOS" not in ID3(mp3_file) and "discnumber" not in FLAC(flac_file)

    tag_file(mp3_file, many, many.tracks[1])
    tag_file(flac_file, many, many.tracks[1])
    assert ID3(mp3_file)["TPOS"].text == ["2"] and FLAC(flac_file)["discnumber"] == ["2"]


def test_lyrics_are_written_and_read_back_in_both(flac_file, mp3_file):
    plan = make_plan()
    words = "[00:01.00] a line\n[00:02.00] and another"

    for path in (flac_file, mp3_file):
        tag_file(path, plan, plan.tracks[0], lyrics=words)
        assert tagged_lyrics(path) == words, path.suffix


