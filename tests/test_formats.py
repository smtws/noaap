def with_history(path: Path) -> Path:
    """What a folder someone has been keeping looks like: fields this program does not model."""
    if kind(path) == "mp3":
        from mutagen.id3 import TBPM, TCOM, TSRC, TXXX, USLT
        tags = ID3(path) if MP3(path).tags else ID3()
        tags.add(TCOM(encoding=3, text=["A composer"]))
        tags.add(TBPM(encoding=3, text=["128"]))
        tags.add(TSRC(encoding=3, text=["DEA621200001"]))
        tags.add(TXXX(encoding=3, desc="replaygain_track_gain", text=["-7.5 dB"]))
        tags.add(TXXX(encoding=3, desc="MusicBrainz Album Id", text=["theirs-not-ours"]))
        tags.add(USLT(encoding=3, lang="eng", desc="", text="their own words"))
        tags.save(path)
    else:
        tags = FLAC(path)
        tags["composer"] = ["A composer"]
        tags["bpm"] = ["128"]
        tags["isrc"] = ["DEA621200001"]
        tags["replaygain_track_gain"] = ["-7.5 dB"]
        tags["musicbrainz_albumid"] = ["theirs-not-ours"]
        tags["lyrics"] = ["their own words"]
        tags.save()
    return path


@pytest.mark.parametrize("fixture", ["flac_file", "mp3_file"])
def test_intake_keeps_what_it_does_not_understand(fixture, request):
    """`keep_unknown` is the difference between taking a collection in and taking it apart."""
    path = with_history(request.getfixturevalue(fixture))
    plan = make_plan()
    plan.mbid = "ours-from-musicbrainz"

    tag_file(path, plan, plan.tracks[0], keep_unknown=True)

    if kind(path) == "mp3":
        tags = ID3(path)
        assert tags["TCOM"].text == ["A composer"] and tags["TBPM"].text == ["128"]
        assert tags["TSRC"].text == ["DEA621200001"]
        assert tags["TXXX:replaygain_track_gain"].text == ["-7.5 dB"]
        assert tags["TIT2"].text == ["T1"], "and the plan's own fields are written"
        assert tags["TXXX:MusicBrainz Album Id"].text == ["theirs-not-ours"]
        assert next(f for f in tags.values() if f.FrameID == "USLT").text == "their own words"
    else:
        tags = FLAC(path)
        assert tags["composer"] == ["A composer"] and tags["bpm"] == ["128"]
        assert tags["isrc"] == ["DEA621200001"]
        assert tags["replaygain_track_gain"] == ["-7.5 dB"]
        assert tags["title"] == ["T1"]
        assert tags["musicbrainz_albumid"] == ["theirs-not-ours"]
        assert tags["lyrics"] == ["their own words"]


@pytest.mark.parametrize("fixture", ["flac_file", "mp3_file"])
def test_without_it_the_plan_is_the_whole_truth(fixture, request):
    """A file we downloaded carries whatever yt-dlp put there and nothing worth keeping."""
    path = with_history(request.getfixturevalue(fixture))
    plan = make_plan()
    plan.mbid = "ours-from-musicbrainz"

    tag_file(path, plan, plan.tracks[0])

    if kind(path) == "mp3":
        tags = ID3(path)
        assert "TCOM" not in tags and "TSRC" not in tags
        assert tags["TXXX:MusicBrainz Album Id"].text == ["ours-from-musicbrainz"]
        assert not [f for f in tags.values() if f.FrameID == "USLT"]
    else:
        tags = FLAC(path)
        assert "composer" not in tags and "isrc" not in tags
        assert tags["musicbrainz_albumid"] == ["ours-from-musicbrainz"]
        assert "lyrics" not in tags


